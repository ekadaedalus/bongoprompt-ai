// Types shared by the API routes and the page. No server-only imports here.

/** Where a piece of data came from. Every listing shows one of these as a tag. */
export type DataSource = "agoda" | "railway" | "openmeteo" | "wikipedia" | "ai" | "bongoprompt";

/** What we understood from the traveller's request, after defaults and the budget split. */
export interface TripRequest {
  origin: string | null;
  destination: string | null;
  checkinDate: string; // YYYY-MM-DD
  checkoutDate: string; // YYYY-MM-DD
  nights: number;
  travellers: number;
  rooms: number;
  total_budget: number | null;
  transport_budget: number | null; // 30% of total_budget
  hotel_budget: number | null; // 70% of total_budget
  needs_origin: boolean;
}

export interface Hotel {
  id: string;
  name: string;
  starRating: number;
  location: string;
  fullAddress: string;
  price: number; // per room per night, BDT
  roomName?: string; // room type the price is for, e.g. "Basic Triple Room"
  occupancy?: number; // guests per room in Agoda's offer
  rooms: number; // rooms needed for all travellers
  stayTotal: number; // price × nights × rooms, BDT
  overBudgetBy: number; // stayTotal minus hotel_budget, 0 when within budget
  image: string;
  amenities: string[];
  isAvailable: boolean;
  latitude?: number;
  longitude?: number;
  bookingUrl?: string;
}

export interface TrainFare {
  cls: string; // e.g. S_CHAIR
  label: string; // e.g. Shovan Chair
  fare: number; // per person incl. VAT, BDT
}

export interface TransportOption {
  id: string;
  type: "Bus" | "Train" | "Flight";
  provider: string;
  departure_time: string;
  arrival_time: string;
  duration: string;
  price: number; // per person, BDT
  departure_station: string;
  arrival_station: string;
  source: "railway" | "ai";
  train_number?: string;
  off_days?: string;
  fares?: TrainFare[];
  fare_class?: string;
  booking_url?: string;
}

export interface LocalGuide {
  id: string;
  name: string;
  specialty: string;
  hourly_rate: number;
  rating?: number;
  bio: string;
  phone?: string;
  /** "sample" = AI-written placeholder, "registered" = a real person who signed up. */
  kind: "sample" | "registered";
}

export interface WeatherDay {
  date: string;
  max: number;
  min: number;
  rain: number; // max precipitation probability, %
  code: number; // WMO weather code
  sunrise: string;
  sunset: string;
}

export type Weather =
  | { status: "ok"; days: WeatherDay[]; tip: string }
  | { status: "too_far" };

export interface DestinationInfo {
  title: string;
  extract: string;
  image?: string;
  url: string;
}

export interface ItineraryDay {
  day: number;
  morning: string;
  afternoon: string;
  evening: string;
  food: string;
}

export type TripStatus = "upcoming" | "booked" | "completed" | "cancelled";
export const TRIP_STATUSES: TripStatus[] = ["upcoming", "booked", "completed", "cancelled"];

/** A confirmed plan, as saved in the trips table and shown on the trip pass. */
export interface TripRecord {
  id: string; // e.g. BT-7K2QXM, generated by the server on confirm
  createdAt: string;
  /** As shown: a past checkout reads "completed" unless the trip was cancelled. */
  status: TripStatus;
  request: TripRequest;
  transport: TransportOption;
  hotel: Hotel;
  guide: LocalGuide | null;
  guideHours: number;
  costs: { transport: number; hotel: number; guide: number; total: number };
  itinerary: ItineraryDay[];
}

/** One line of the NDJSON stream from /api/parse-prompt. */
export type PlanEvent =
  | { type: "steps"; steps: { id: string; label: string }[] }
  | { type: "step"; id: string; status: "done" | "failed" | "skipped"; note?: string }
  | { type: "request"; request: TripRequest }
  | { type: "hotels"; hotels: Hotel[] }
  | { type: "transport"; options: TransportOption[] } // AI-estimated buses and flights
  | { type: "trains"; options: TransportOption[] } // real Bangladesh Railway trains
  | { type: "guides"; guides: LocalGuide[] }
  | { type: "weather"; weather: Weather }
  | { type: "destination"; info: DestinationInfo }
  | { type: "itinerary"; days: ItineraryDay[] }
  | { type: "error"; message: string }
  | { type: "end" };
